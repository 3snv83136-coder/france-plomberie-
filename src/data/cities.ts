// Cross-department neighborhoods (Paris is its own department, so its real
// neighbors live in 92/93/94).
const NEARBY_OVERRIDES: Record<string, string[]> = {
  paris: ["boulogne-billancourt", "saint-denis", "montreuil", "vincennes", "neuilly-sur-seine"],
};

function slugify(str: string): string {
  return str
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/['']/g, "-")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function buildCities(): City[] {
  const list: City[] = [];
  const seenSlugs = new Set<string>();
  const byDept = new Map<string, City[]>();

  for (const [deptCode, communes] of Object.entries(COMMUNES_RAW)) {
    const dept = DEPARTMENTS.find((d) => d.code === deptCode);
    if (!dept) continue;
    const regionName = REGIONS.find((r) => r.slug === dept.region)?.name ?? "";
    const deptList: City[] = [];

    for (const c of communes) {
      const [name, postalCode, population, insee, lat, lng] = c;
      let slug = slugify(name);
      // Disambiguate across departments if needed
      if (seenSlugs.has(slug)) slug = `${slug}-${deptCode.toLowerCase()}`;
      if (seenSlugs.has(slug)) continue; // skip duplicates safely
      seenSlugs.add(slug);

      const city: City = {
        slug,
        name,
        insee: insee ?? null,
        postalCode,
        population,
        lat: lat ?? null,
        lng: lng ?? null,
        department: { code: dept.code, name: dept.name },
        region: regionName,
        nearby: [],
      };
      deptList.push(city);
      list.push(city);
    }

    byDept.set(deptCode, deptList);
  }

  // Auto-generate nearby: top 5 communes of same department, fallback to same
  // region if department has fewer than 5 entries.
  const byRegion = new Map<string, City[]>();
  for (const city of list) {
    const arr = byRegion.get(city.region) ?? [];
    arr.push(city);
    byRegion.set(city.region, arr);
  }

  for (const city of list) {
    if (NEARBY_OVERRIDES[city.slug]) {
      city.nearby = NEARBY_OVERRIDES[city.slug];
      continue;
    }
    const sameDept = (byDept.get(city.department.code) ?? [])
      .filter((c) => c.slug !== city.slug)
      .sort((a, b) => b.population - a.population);
    if (sameDept.length >= 5) {
      city.nearby = sameDept.slice(0, 5).map((c) => c.slug);
      continue;
    }
    const fillers = (byRegion.get(city.region) ?? [])
      .filter((c) => c.slug !== city.slug && !sameDept.some((s) => s.slug === c.slug))
      .sort((a, b) => b.population - a.population)
      .slice(0, 5 - sameDept.length)
      .map((c) => c.slug);
    city.nearby = [...sameDept.map((c) => c.slug), ...fillers];
  }

  // Sort: largest first (helps SEO listings of "top cities").
  list.sort((a, b) => b.population - a.population);
  return list;
}

export const CITIES: City[] = buildCities();

export function getCityBySlug(slug: string): City | undefined {
  return CITIES.find((c) => c.slug === slug);
}
